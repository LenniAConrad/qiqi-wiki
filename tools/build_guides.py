"""Render the task-based player guides from data/guides.json.

Writes guides.html (the index) and one guide-<slug>.html per guide. Guides are
plain structured data so their facts stay checkable: they cite ledger feature
ids from data/features.json, take every control of the full controls reference
from that ledger, and take every recipe from data/recipes.json. Each page is
complete without JavaScript; guides.js only adds a filter to the controls
reference. The output is deterministic; tools/validate_guides.py rebuilds it in
memory and requires the committed pages to match exactly.

Inline markup in text fields: [[W]] renders a key cap, **text** is bold, {{feature-id}} or
{{feature-id|label}} links to that feature's ledger entry, and
{{guide:slug|label}} links to another guide.
"""

import argparse
from base_game import public_ledger
from wiki_layout import header_html, footer_html
from html import escape
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
GUIDES = ROOT / "data" / "guides.json"
FEATURES = ROOT / "data" / "features.json"
RECIPES = ROOT / "data" / "recipes.json"
INDEX_PAGE = "guides.html"

MODE_LABELS = {"creative": "Creative", "survival": "Survival", "menu": "Menus", "any": "Any mode"}
MONTHS = ("January", "February", "March", "April", "May", "June", "July",
          "August", "September", "October", "November", "December")
NOTE_LABELS = {"tip": "Tip", "careful": "Careful", "limit": "Good to know", "planned": "Planned, not in the game"}
KEY_RE = re.compile(r"\[\[(.+?)\]\]")
BOLD_RE = re.compile(r"\*\*(.+?)\*\*")
LINK_RE = re.compile(r"\{\{(.+?)\}\}")


def text(value):
    return escape(str(value), quote=False)


def attr(value):
    return escape(str(value), quote=True)


def long_date(iso_date):
    year, month, day = (int(part) for part in iso_date[:10].split("-"))
    return f"{day} {MONTHS[month - 1]} {year}"


class Context:
    """Lookup tables shared by every page of one build."""

    def __init__(self, guides, ledger, recipes):
        self.guides = guides
        ledger = public_ledger(ledger)
        self.ledger = ledger
        self.recipes = recipes
        self.features = {feature["id"]: feature for feature in ledger["features"]}
        self.areas = {area["key"]: area for area in ledger["areas"]}
        self.statuses = {status["key"]: status for status in ledger["statuses"]}
        self.by_slug = {guide["id"]: guide for guide in guides["guides"]}

    def inline(self, raw):
        """Escape one text field and expand its key caps and links."""
        value = text(raw)
        value = KEY_RE.sub(lambda match: f"<kbd>{match.group(1)}</kbd>", value)
        value = BOLD_RE.sub(lambda match: f"<strong>{match.group(1)}</strong>", value)

        def link(match):
            target, _, label = match.group(1).partition("|")
            if target.startswith("guide:"):
                guide = self.by_slug[target[6:]]
                return f'<a href="{attr(guide["page"])}">{label or text(guide["title"])}</a>'
            feature = self.features[target]
            return f'<a href="features.html#f-{attr(target)}">{label or text(feature["name"])}</a>'

        return LINK_RE.sub(link, value)


def page_open(title, description, nav_current, body_class, skip_target, skip_label, edition, script=False):
    return (
        "<!doctype html>\n<!-- SPDX-License-Identifier: GPL-3.0-only -->\n"
        "<!-- Generated by tools/build_guides.py from data/guides.json. Do not edit by hand. -->\n"
        '<html lang="en">\n<head>\n'
        '<meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1">\n'
        f'<meta name="description" content="{attr(description)}">\n'
        f'<meta name="theme-color" content="#253c30"><title>{text(title)} · Qiqi wiki</title>\n'
        '<link rel="icon" href="favicon.svg" type="image/svg+xml"><link rel="stylesheet" href="style.css">'
        '<link rel="stylesheet" href="features.css"><link rel="stylesheet" href="guides.css">'
        '<link rel="stylesheet" href="wiki.css">\n'
        + ('<script defer src="guides.js"></script>\n' if script else "") +
        f'</head>\n<body class="{body_class}">\n'
        f'<a class="skip" href="#{skip_target}">{text(skip_label)}</a>\n'
        + header_html(nav_current) + '\n<main>\n')


def page_close():
    return '</main>\n' + footer_html() + '\n</body></html>\n'


def key_rows(ctx, rows):
    items = "".join(
        f"<tr><th scope=\"row\"><kbd>{text(key)}</kbd></th><td data-label=\"What it does\">{ctx.inline(action)}</td></tr>"
        for key, action in rows)
    return ('<div class="table-wrap"><table class="key-table"><thead><tr><th scope="col">Key or action</th>'
            f'<th scope="col">What it does</th></tr></thead><tbody>{items}</tbody></table></div>')


def recipe_cell(items):
    return "<ul class=\"recipe-inputs\">" + "".join(
        f"<li><span class=\"recipe-count\">{count}×</span> {text(item)}</li>" for item, count in items) + "</ul>"


def recipe_tables(ctx, block):
    wanted = block.get("sections") or [section["key"] for section in ctx.recipes["sections"]]
    names = block.get("names")
    parts = []
    for section in ctx.recipes["sections"]:
        if section["key"] not in wanted:
            continue
        members = [recipe for recipe in ctx.recipes["recipes"] if recipe["section"] == section["key"]
                   and (names is None or recipe["name"] in names)]
        if not members:
            continue
        rows = []
        for recipe in members:
            note = f'<p class="recipe-note">{ctx.inline(recipe["notes"])}</p>' if recipe.get("notes") else ""
            rows.append(
                f'<tr><th scope="row">{text(recipe["name"])}</th>'
                f'<td data-label="Makes"><span class="recipe-count">{recipe["quantity"]}×</span> {text(recipe["output"])}</td>'
                f'<td data-label="Needs">{recipe_cell(recipe["inputs"])}{note}</td></tr>')
        parts.append(
            f'<div class="table-wrap"><table class="recipe-table"><caption>{text(section["label"])} '
            f'<span class="caption-count">{len(members)} recipes</span></caption><thead><tr>'
            '<th scope="col">Recipe</th><th scope="col">Makes</th><th scope="col">Needs</th></tr></thead>'
            f'<tbody>{"".join(rows)}</tbody></table></div>')
    return "".join(parts)


def controls_reference(ctx, block):
    """Every control in the ledger, grouped by area, filterable in the browser."""
    out = ['<div class="toolbar" id="controls-tools" hidden><label class="search-label"><span aria-hidden="true">⌕</span>'
           '<input id="controls-search" type="search" placeholder="Find a key or action…" aria-label="Search controls"'
           ' autocomplete="off"><kbd aria-hidden="true">/</kbd></label>'
           '<p id="controls-count" role="status" aria-live="polite"></p></div>']
    total = 0
    for area in ctx.ledger["areas"]:
        rows = []
        for feature in ctx.ledger["features"]:
            if feature["area"] != area["key"] or not feature.get("controls"):
                continue
            status = ctx.statuses[feature["status"]]
            modes = " · ".join(MODE_LABELS[mode] for mode in feature.get("modes", []))
            badge = ""
            if status["key"] != "available":
                badge = f' <span class="status status-{attr(status["key"])}">{text(status["label"])}</span>'
            for key, action in feature["controls"]:
                total += 1
                search = f"{key} {action} {feature['name']} {modes} {area['label']}".lower()
                rows.append(
                    f'<tr class="control-row" data-search="{attr(search)}"><th scope="row"><kbd>{text(key)}</kbd></th>'
                    f'<td data-label="What it does, and when">{text(action)}</td>'
                    f'<td data-label="Feature"><a href="features.html#f-{attr(feature["id"])}">{text(feature["name"])}</a>{badge}'
                    f'<span class="control-modes">{text(modes)}</span></td></tr>')
        if not rows:
            continue
        out.append(
            f'<section class="control-group" id="controls-{attr(area["key"])}" aria-labelledby="controls-{attr(area["key"])}-t">'
            f'<h3 id="controls-{attr(area["key"])}-t">{text(area["label"])}</h3>'
            f'<div class="table-wrap"><table class="key-table controls-table"><thead><tr><th scope="col">Key or action</th>'
            f'<th scope="col">What it does, and when</th><th scope="col">Feature</th></tr></thead>'
            f'<tbody>{"".join(rows)}</tbody></table></div></section>')
    out.append('<p id="controls-empty" class="empty-line" hidden>No control matches. Try another word.</p>')
    out.append(f'<p class="measurement-note" id="controls-total">{total} controls listed from the audited ledger.</p>')
    return "".join(out)


def figure(ctx, block):
    width, height = block.get("size", [1280, 720])
    return (f'<figure class="guide-figure"><img src="{attr(block["src"])}" width="{width}" height="{height}"'
            f' alt="{attr(block["alt"])}" loading="lazy" decoding="async"><figcaption>{ctx.inline(block["caption"])}'
            "</figcaption></figure>")


def block_html(ctx, block):
    kind = block["t"]
    if kind == "p":
        return f'<p>{ctx.inline(block["text"])}</p>'
    if kind == "h":
        return f'<h3>{ctx.inline(block["text"])}</h3>'
    if kind == "steps":
        return '<ol class="guide-steps">' + "".join(f"<li>{ctx.inline(item)}</li>" for item in block["items"]) + "</ol>"
    if kind == "list":
        return '<ul class="guide-list">' + "".join(f"<li>{ctx.inline(item)}</li>" for item in block["items"]) + "</ul>"
    if kind == "note":
        label = NOTE_LABELS[block["kind"]]
        return (f'<aside class="guide-note guide-note-{attr(block["kind"])}"><strong>{text(label)}.</strong> '
                f'{ctx.inline(block["text"])}</aside>')
    if kind == "keys":
        return key_rows(ctx, block["rows"])
    if kind == "figure":
        return figure(ctx, block)
    if kind == "recipes":
        return recipe_tables(ctx, block)
    if kind == "controls-all":
        return controls_reference(ctx, block)
    raise ValueError(f"unknown block type {kind!r}")


def verification_html(ctx, guide):
    game = ctx.ledger["game"]
    verification = guide["verification"]
    covered = ", ".join(
        f'<a href="features.html#f-{attr(item)}">{text(ctx.features[item]["name"])}</a>' for item in guide["covers"])
    return (
        '<section id="verification" class="guide-section guide-verification" aria-labelledby="verification-t">'
        '<h2 id="verification-t">How this guide was checked</h2>'
        f'<p>{ctx.inline(verification["method"])}</p>'
        f'<p class="measurement-note">Voxelgame main <code>{text(game["commit"][:7])}</code>, committed '
        f'{text(long_date(game["commitDate"]))}; guide written {text(long_date(guide["updated"]))}. '
        f'{ctx.inline(verification["limits"])} Features covered, with their source evidence: {covered}.</p>'
        "</section>\n")


def render_guide(ctx, guide):
    sections = guide["sections"]
    scripted = any(block["t"] == "controls-all" for section in sections for block in section["blocks"])
    out = [page_open(guide["title"], guide["summary"], guide["page"], "guide-page", "guide-body",
                     "Skip to the guide", "PLAYER GUIDE", scripted)]
    add = out.append
    add('<nav class="wiki-breadcrumb" aria-label="Breadcrumb"><a href="index.html">Home</a>'
        f'<span aria-hidden="true">/</span><a href="guides.html">Guides</a><span aria-hidden="true">/</span>'
        f'<span aria-current="page">{text(guide["title"])}</span></nav>')
    add('<section class="intro" aria-labelledby="title"><div class="intro-row">'
        f'<h1 id="title">{text(guide["title"])}</h1><p>{ctx.inline(guide["lead"])}</p></div></section>\n')
    game = ctx.ledger["game"]
    add(f'<div class="study-meta">Voxelgame main <code>{text(game["commit"][:7])}</code> · {text(guide["readTime"])}'
        f' · {text(guide["audience"])} · <a href="features.html">feature ledger</a> · '
        f'<a href="{INDEX_PAGE}">all guides</a></div>\n')
    add('<article class="wiki-article" aria-labelledby="title"><details class="wiki-contents" open>'
        '<summary>Contents</summary><nav aria-label="On this page"><ol>' + "".join(
        f'<li><a href="#{attr(section["id"])}">{text(section["title"])}</a></li>' for section in sections) +
        '<li><a href="#verification">How this was checked</a></li></ol></nav></details>\n')
    add('<div id="guide-body">\n')
    for section in sections:
        add(f'<section class="guide-section" id="{attr(section["id"])}" aria-labelledby="{attr(section["id"])}-t">'
            f'<h2 id="{attr(section["id"])}-t">{text(section["title"])}</h2>')
        for block in section["blocks"]:
            add(block_html(ctx, block))
        add("</section>\n")
    add(verification_html(ctx, guide))
    related = [ctx.by_slug[slug] for slug in guide.get("next", [])]
    if related:
        add('<section class="guide-section" aria-labelledby="next-t"><h2 id="next-t">Keep going</h2><ul class="guide-list">')
        for item in related:
            add(f'<li><a href="{attr(item["page"])}">{text(item["title"])}</a>: {text(item["summary"])}</li>')
        add("</ul></section>\n")
    add("</div></article>\n")
    add(page_close())
    return "".join(out)


def render_index(ctx):
    ledger = ctx.ledger
    guides = ctx.guides
    out = [page_open("Player guides", guides["description"], INDEX_PAGE, "guides-index",
                     "guide-list", "Skip to the guide list", "PLAYER GUIDES")]
    add = out.append
    add('<section class="intro" aria-labelledby="title"><div class="eyebrow"><span class="status-dot"></span> '
        f'PLAYER GUIDES / UPDATED {text(long_date(guides["updated"]).upper())}</div><div class="intro-row">'
        f'<h1 id="title">Player guides</h1><p>{text(guides["lead"])}</p></div></section>\n')
    game = ledger["game"]
    add(f'<div class="study-meta">Written against Voxelgame main <code>{text(game["commit"][:7])}</code> · committed '
        f'{text(long_date(game["commitDate"]))} · every claim is traced to the source in the '
        '<a href="features.html">feature ledger</a></div>\n')
    add(f'<section id="guide-list" class="report-section" aria-labelledby="list-t"><div class="section-heading">'
        '<div class="eyebrow">01 / WRITTEN</div><h2 id="list-t">Written guides</h2></div><ol class="guide-cards">')
    for guide in guides["guides"]:
        add(f'<li class="guide-card"><div class="guide-card-meta">GUIDE {guide["number"]:02d} · '
            f'{text(guide["readTime"])} · {text(guide["audience"])}</div>'
            f'<h3><a href="{attr(guide["page"])}">{text(guide["title"])}</a></h3><p>{text(guide["summary"])}</p></li>')
    add("</ol></section>\n")
    written = {guide["gap"] for guide in guides["guides"] if "gap" in guide}
    waiting = [gap for gap in sorted(ledger["guideGaps"], key=lambda item: item["rank"]) if gap["rank"] not in written]
    add('<section id="coming" class="report-section" aria-labelledby="coming-t"><div class="section-heading">'
        '<div class="eyebrow">02 / NOT WRITTEN YET</div><h2 id="coming-t">Not written yet</h2></div>'
        f'<p class="report-lead">{text(guides["comingLead"])}</p><ol class="priority-list gap-list">')
    for gap in waiting:
        add(f'<li value="{gap["rank"]}"><h3>{text(gap["title"])} <span class="readiness readiness-{attr(gap["readiness"])}">'
            f'{text(ledger["readiness"][gap["readiness"]])}</span></h3><p>{text(gap["why"])}</p></li>')
    add("</ol></section>\n")
    add(page_close())
    return "".join(out)


def render_all(guides, ledger, recipes):
    """Return {file name: html} for every generated page."""
    ctx = Context(guides, ledger, recipes)
    pages = {INDEX_PAGE: render_index(ctx)}
    for guide in guides["guides"]:
        pages[guide["page"]] = render_guide(ctx, guide)
    return pages


def load():
    def read(path):
        return json.loads(path.read_text(encoding="utf-8"))

    return read(GUIDES), read(FEATURES), read(RECIPES)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args()
    pages = render_all(*load())
    for name, html in pages.items():
        (ROOT / name).write_text(html, encoding="utf-8")
    print(f"Wrote {len(pages)} pages: {', '.join(pages)}")


if __name__ == "__main__":
    main()
