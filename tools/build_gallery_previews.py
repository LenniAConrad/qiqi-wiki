"""Build responsive derivatives of dated gallery and guide images, without changing originals."""
import argparse
from html import escape
import json
from pathlib import Path

from image_variants import encoder, generate_images, validate_images

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = 'data/gallery-previews.json'
SCRIPT = 'image-previews.js'
CATALOGS = ['data/biomes.json', 'data/animals.json', 'data/guides.json']
# Reviewed separately at displayed sizes. These choices do not apply to new art
# automatically; revisit them when the underlying capture collections change.
PROFILES = {
    'biomes': {'widths': [480, 640], 'resample': 'LANCZOS', 'quality': 90,
               'directory': 'images/thumbnails/biomes', 'originalSize': [960, 540]},
    'animals': {'widths': [72, 144, 192, 320], 'resample': 'LANCZOS', 'quality': 90,
                'directory': 'images/thumbnails/animals', 'originalSize': [512, 512]},
    'guides': {'widths': [640, 960], 'resample': 'LANCZOS', 'quality': 86,
               'directory': 'images/thumbnails/guides', 'originalSize': [1280, 720]},
}


def sources(root=ROOT):
    biomes, animals, guides = [json.loads((root / name).read_text()) for name in CATALOGS]
    result = {b['image']: 'biomes' for b in biomes['biomes']}
    # Only the resting three-quarter portrait is used outside the full viewer.
    for animal in animals['animals']:
        if animal.get('views'):
            view = next((v for v in animal['views'] if v['pose'] == 'idle' and v['angle'] == 'three-quarter'),
                        animal['views'][0])
            assert view == animal['views'][0], 'Gallery and reference must use the same preview view'
            result[view['image']] = 'animals'

    def figures(value):
        if isinstance(value, dict):
            if value.get('t') == 'figure':
                result[value['src']] = 'guides'
            for child in value.values():
                figures(child)
        elif isinstance(value, list):
            for child in value:
                figures(child)
    figures(guides)
    return result


def variants(source, kind, minimum=0):
    settings = PROFILES[kind]
    stem = Path(source).stem
    return [(width, f'{settings["directory"]}/{stem}--{width}.webp')
            for width in settings['widths'] if width >= minimum]


def attributes(source, kind, sizes, minimum=0):
    """Static HTML remains responsive without JavaScript, including file://."""
    choices = variants(source, kind, minimum)
    choices.append((PROFILES[kind]['originalSize'][0], source))
    srcset = ', '.join(f'{path} {width}w' for width, path in choices)
    return f'src="{escape(choices[0][1], quote=True)}" srcset="{escape(srcset, quote=True)}" sizes="{escape(sizes, quote=True)}"'


def browser_script():
    # Predictable local paths avoid downloading a second copy of the catalogs.
    return '''// SPDX-License-Identifier: GPL-3.0-only
// Generated by tools/build_gallery_previews.py; source/derivative hashes are in data/gallery-previews.json.
'use strict';
window.WIKI_IMAGE_PREVIEWS = (() => {
  const profiles = ''' + json.dumps(PROFILES, separators=(',', ':')) + ''';
  function set(image, source, kind, sizes, minimum = 0) {
    const profile = profiles[kind];
    const stem = source.slice(source.lastIndexOf('/') + 1).replace(/\\.[^.]+$/, '');
    const choices = profile.widths.filter(width => width >= minimum).map(width =>
      [width, `${profile.directory}/${stem}--${width}.webp`]);
    choices.push([profile.originalSize[0], source]);
    // Select responsive candidates before assigning the fallback src.
    image.sizes = sizes;
    image.srcset = choices.map(([width, path]) => `${path} ${width}w`).join(', ');
    image.src = choices[0][1];
  }
  return {set};
})();
'''


def generate(root=ROOT):
    images = generate_images(root, sources(root), PROFILES)
    manifest = {'schema': 1, 'catalogs': CATALOGS, 'profiles': PROFILES, 'encoder': encoder(), 'images': images}
    (root / MANIFEST).write_text(json.dumps(manifest, indent=2) + '\n')
    (root / SCRIPT).write_text(browser_script())
    return manifest


def validate(root=ROOT):
    manifest = json.loads((root / MANIFEST).read_text())
    assert manifest['schema'] == 1 and manifest['profiles'] == PROFILES, 'Stale preview policy'
    assert manifest['catalogs'] == CATALOGS, 'Wrong preview catalogs'
    validate_images(root, manifest['images'], sources(root), PROFILES)
    for entry in manifest['images']:
        assert [entry['sourceWidth'], entry['sourceHeight']] == PROFILES[entry['kind']]['originalSize'], \
            'Capture dimensions changed; review responsive sizes and filters'
        assert all(v['bytes'] < (root / entry['source']).stat().st_size for v in entry['variants']), \
            f'Preview is not smaller than its original; review encoding: {entry["source"]}'
    assert (root / SCRIPT).read_text() == browser_script(), 'Stale responsive-image script'
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    manifest = validate() if args.check else generate()
    previews = [v for entry in manifest['images'] for v in entry['variants']]
    print(f'{"Validated" if args.check else "Built"} {len(previews)} gallery/guide previews, '
          f'{sum(v["bytes"] for v in previews):,} bytes; original capture receipts unchanged')


if __name__ == '__main__':
    main()
