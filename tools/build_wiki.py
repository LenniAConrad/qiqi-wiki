def render_topic(topic):
    guides = {guide['id']: guide for guide in read('guides')['guides']}
    sections = ([('articles', 'Guides')] if topic['guides'] else []) + [
        ('reference', 'Quick reference'), ('related-topics', 'Related topics')]
    out = [article_open(topic['title'], topic['page'], topic['summary'], sections, 'build_wiki.py')]
    if topic['guides']:
        out.append('<section class="guide-section" id="articles"><h2>Guides</h2><ul class="topic-articles">')
        for slug in topic['guides']:
            guide = guides[slug]
            out.append(f'<li><h3><a href="{guide["page"]}">{escape(guide["title"])}</a></h3>'
                       f'<p>{escape(guide["summary"])}</p><span>{escape(guide["readTime"])}</span></li>')
        out.append('</ul></section>')
    out.append('<section class="guide-section" id="reference"><h2>Quick reference</h2><ul class="quick-links">')
    for href, label in topic['references']:
        out.append(f'<li><a href="{href}">{escape(label)}</a></li>')
    out.append('</ul></section><section class="guide-section" id="related-topics"><h2>Related topics</h2>'
               '<ul class="related-topics">')
    topics = {entry['id']: entry for entry in TOPICS}
    for key in topic['related']:
        other = topics[key]
        out.append(f'<li><a href="{other["page"]}">{escape(other["title"])}</a></li>')
    out.append('</ul></section>' + article_close())
    return ''.join(out)


def apply_chrome(value, page):
    value = re.sub(r'<header class="site-header">.*?</header>', header_html(page), value, count=1, flags=re.S)
    value = re.sub(r'<footer>.*?</footer>', footer_html(), value, count=1, flags=re.S)
    if 'href="wiki.css"' not in value:
        value = value.replace('</head>', '<link rel="stylesheet" href="wiki.css">\n</head>')
    if 'src="wiki-ui.js"' not in value:
        value = value.replace('</head>', '<script defer src="wiki-ui.js"></script>\n</head>')
    if page == 'islands.html' and 'src="data/island-thumbnails.js"' not in value:
        value = value.replace('<script defer src="islands.js">',
                              '<script defer src="data/island-thumbnails.js"></script><script defer src="islands.js">')
    if page in ('atlas.html', 'animals.html') and 'src="image-previews.js"' not in value:
        script = 'app.js' if page == 'atlas.html' else 'animals.js'
        value = value.replace(f'<script defer src="{script}">',
                              f'<script defer src="image-previews.js"></script><script defer src="{script}">')
    if page == 'atlas.html':
        catalog = read('biomes')
        featured = next(b for b in catalog['biomes'] if b['id'] == catalog['featuredId'])
        attrs = preview_attributes(featured['image'], 'biomes',
                                   '(max-width: 650px) 88vw, (min-width: 1500px) 1300px, 89vw')
        value = re.sub(r'<img id="hero-image"[^>]*>',
                       f'<img id="hero-image" {attrs} alt="{escape(featured["name"])}" '
                       'fetchpriority="high" decoding="async" width="960" height="540">', value)
    return value.replace('index.html#catalog', 'atlas.html#catalog').replace('· qiqi-dev', '· Qiqi wiki')


def main():
    (ROOT / 'index.html').write_text(render_home())
    (ROOT / 'data/search.js').write_text(search_script())
    for topic in TOPICS:
        (ROOT / topic['page']).write_text(render_topic(topic))
    for page, _ in ATLAS:
        path = ROOT / page
        path.write_text(apply_chrome(path.read_text(), page))
    print(f'Built wiki home, {len(search_records())} offline search records and shared atlas navigation')


if __name__ == '__main__':
    main()
