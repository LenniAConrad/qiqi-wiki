"""Build the wiki home, offline search index and shared atlas navigation."""
from html import escape
import json
from pathlib import Path
import re

from base_game import public_ledger
from wiki_layout import ATLAS, CATEGORIES, header_html, footer_html

ROOT = Path(__file__).resolve().parents[1]


def read(name):
    return json.loads((ROOT / f'data/{name}.json').read_text())


def search_records():
    records = []

    def add(title, description, href, kind):
        records.append(dict(title=title, text=description, href=href, kind=kind))

    for guide in read('guides')['guides']:
        add(guide['title'], guide['summary'], guide['page'], 'Guide')
    for feature in public_ledger(read('features'))['features']:
        controls = ' '.join(f'{key}: {action}' for key, action in feature.get('controls', []))
        add(feature['name'], feature['summary'] + (' ' + controls if controls else ''),
            f'features.html#f-{feature["id"]}', 'Feature')
    for recipe in read('recipes')['recipes']:
        ingredients = ', '.join(f'{count}× {item}' for item, count in recipe['inputs'])
        add(recipe['name'], f'{recipe["quantity"]}× {recipe["output"]}; needs {ingredients}.',
            'guide-crafting.html#recipes', 'Recipe')
    for biome in read('biomes')['biomes']:
        add(biome['name'], biome['description'], f'atlas.html#biome={biome["id"]}', 'Biome atlas')
    return records


def search_script():
    return '/* SPDX-License-Identifier: GPL-3.0-only */\nwindow.QIQI_SEARCH = ' + json.dumps(
        search_records(), ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c') + ';\n'


def render_home():
    ledger = public_ledger(read('features'))
    cards = []
    summaries = {'getting-started': 'Create a world, move, save and switch game modes.',
                 'controls': 'Keys and actions, with the context each one needs.',
                 'crafting': 'The crafting panel and 37 recipes with exact amounts.'}
    for key, title, page in CATEGORIES:
        heading = f'<a href="{page}">{title}</a>' if page else title
        description = summaries.get(key, 'Not written yet')
        related = ('<p class="category-related"><a href="guide-first-survival-day.html">Your first survival day</a></p>'
                   if key == 'getting-started' else '')
        cards.append(f'<li id="{key}"><h3>{heading}</h3><p>{description}</p>{related}</li>')
    atlas_links = ''.join(f'<li><a href="{href}">{label}</a></li>' for href, label in ATLAS)
    return ('<!doctype html>\n<!-- SPDX-License-Identifier: GPL-3.0-only -->\n'
            '<!-- Generated by tools/build_wiki.py. -->\n<html lang="en"><head>\n'
            '<meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
            '<meta name="description" content="Qiqi: a Voxelgame player wiki. Guides, controls, crafting and the world atlas.">'
            '<meta name="theme-color" content="#253c30"><title>Qiqi · Voxelgame wiki</title>'
            '<link rel="icon" href="favicon.svg" type="image/svg+xml">'
            '<link rel="stylesheet" href="style.css"><link rel="stylesheet" href="wiki.css">'
            '<script defer src="data/search.js"></script><script defer src="wiki-search.js"></script>'
            '</head><body class="wiki-home"><a class="skip" href="#categories">Skip to categories</a>'
            + header_html('index.html') + '<main>\n<h1>Voxelgame</h1>'
            '<p class="home-description">An original voxel sandbox for building, exploring islands and playing in creative or survival mode.</p>'
            '<div class="wiki-search" id="wiki-search-panel" hidden><label for="wiki-search">Search the wiki</label>'
            '<input id="wiki-search" type="search" autocomplete="off" placeholder="Try stone axe, swimming or pine…" '
            'aria-describedby="search-help" aria-controls="search-results">'
            '<p class="search-help" id="search-help">Press / to search, Enter to focus the first result, or Escape to clear.</p>'
            '<p id="search-status" role="status" aria-live="polite" class="search-help"></p>'
            '<ol id="search-results" class="search-results" hidden></ol></div>'
            '<noscript><p>Browse the categories below or use your browser’s Find command in the '
            '<a href="features.html">feature ledger</a>.</p></noscript>'
            '<section id="categories" aria-labelledby="categories-title"><h2 id="categories-title">Player guides</h2>'
            '<ul class="category-grid">' + ''.join(cards) + '</ul>'
            '<p><a href="guides.html">All written guides and writing gaps</a></p></section>'
            '<section class="home-atlas" aria-labelledby="atlas-title"><h2 id="atlas-title"><a href="atlas.html">Atlas</a></h2>'
            '<p>Biomes, animal models, island maps, world scale and dated performance measurements. '
            'Each gallery keeps its own snapshot and provenance.</p><ul class="atlas-links">' + atlas_links + '</ul></section>'
            f'<p class="home-receipt">Base-game coverage: {len(ledger["features"])} features listed at audited game commit '
            f'<code>{ledger["game"]["commit"][:7]}</code>, audited {ledger["audited"]}. '
            'The guides are source checked; their limits are recorded with each article.</p>'
            '</main>' + footer_html() + '</body></html>\n')


def apply_chrome(value, page):
    value = re.sub(r'<header class="site-header">.*?</header>', header_html(page), value, count=1, flags=re.S)
    value = re.sub(r'<footer>.*?</footer>', footer_html(), value, count=1, flags=re.S)
    if 'href="wiki.css"' not in value:
        value = value.replace('</head>', '<link rel="stylesheet" href="wiki.css">\n</head>')
    return value.replace('index.html#catalog', 'atlas.html#catalog').replace('· qiqi-dev', '· Qiqi wiki')


def main():
    (ROOT / 'index.html').write_text(render_home())
    (ROOT / 'data/search.js').write_text(search_script())
    for page, _ in ATLAS:
        path = ROOT / page
        path.write_text(apply_chrome(path.read_text(), page))
    print(f'Built wiki home, {len(search_records())} offline search records and shared atlas navigation')


if __name__ == '__main__':
    main()
